CREATE TABLE IF NOT EXISTS time_entries (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    organization_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    project_id BIGINT UNSIGNED NOT NULL,
    task_id BIGINT UNSIGNED NULL,
    client_id BIGINT UNSIGNED NULL,
    started_at DATETIME NOT NULL,
    ended_at DATETIME NULL,
    duration_minutes INT UNSIGNED NULL,
    note VARCHAR(2000) NULL,
    billable TINYINT(1) NOT NULL DEFAULT 1,
    source VARCHAR(20) NOT NULL DEFAULT 'manual',
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_time_org_user_started (organization_id, user_id, started_at),
    KEY idx_time_org_project (organization_id, project_id, started_at),
    KEY idx_time_task (task_id),
    KEY idx_time_running (organization_id, user_id, ended_at),
    CONSTRAINT fk_time_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_time_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_time_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_time_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE SET NULL,
    CONSTRAINT fk_time_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE SET NULL
);
